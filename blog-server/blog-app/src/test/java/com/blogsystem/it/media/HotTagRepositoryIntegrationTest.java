package com.blogsystem.it.media;

import com.baomidou.mybatisplus.core.MybatisConfiguration;
import com.baomidou.mybatisplus.core.config.GlobalConfig;
import com.baomidou.mybatisplus.core.toolkit.GlobalConfigUtils;
import com.baomidou.mybatisplus.extension.spring.MybatisSqlSessionFactoryBean;
import com.blogsystem.domain.content.model.TagDefinition;
import com.blogsystem.infrastructure.adapter.repository.content.MybatisTaxonomyRepository;
import com.blogsystem.infrastructure.mybatis.mapper.content.TagMapper;
import com.blogsystem.infrastructure.mybatis.mapper.content.CategoryMapper;
import com.blogsystem.test.RepositoryPaths;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import java.util.List;
import static org.junit.jupiter.api.Assertions.*;

class HotTagRepositoryIntegrationTest {
    static final String MIGRATION="010_20261017_move_home_tag_selection_to_tag_is_hot.sql";
    static void setup(MediaPostgresTestSupport.ScopedSchema schema) throws Exception {
        schema.execute("CREATE TABLE tag(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name VARCHAR(100),slug VARCHAR(100),color VARCHAR(32),sort INTEGER DEFAULT 0,status SMALLINT DEFAULT 1,deleted SMALLINT DEFAULT 0,created_at TIMESTAMP,updated_at TIMESTAMP)");
        schema.execute("INSERT INTO tag(name,slug) VALUES('one','one'),('two','two'),('three','three'),('four','four')");
        schema.executeDdl(RepositoryPaths.file("migration","009_20261017_add_home_tag_selection.sql"));
    }
    static SqlSessionFactory factory(String schema) throws Exception {
        var config=new MybatisConfiguration();config.setMapUnderscoreToCamelCase(true);
        var global=new GlobalConfig().setDbConfig(new GlobalConfig.DbConfig().setLogicDeleteField("deleted").setLogicDeleteValue("1").setLogicNotDeleteValue("0"));
        GlobalConfigUtils.setGlobalConfig(config,global);
        config.addMapper(TagMapper.class);config.addMapper(CategoryMapper.class);
        var factory=new MybatisSqlSessionFactoryBean();factory.setConfiguration(config);factory.setGlobalConfig(global);
        factory.setDataSource(new DriverManagerDataSource(System.getenv("MEDIA_PG_TEST_URL")+"?currentSchema="+schema,
                System.getenv("MEDIA_PG_TEST_USERNAME"),System.getenv("MEDIA_PG_TEST_PASSWORD")));
        return factory.getObject();
    }
    @Test void migrationPreservesExistingSelectionAndOtherDataAndDropsOnlyRetiredConfig() throws Exception {
        try(var schema=MediaPostgresTestSupport.createSchema()) {
            setup(schema);
            schema.execute("UPDATE home_tag_selection SET first_tag_id=3,second_tag_id=1,third_tag_id=2");
            schema.executeDdl(RepositoryPaths.file("migration",MIGRATION));
            try(var connection=schema.openConnection();var statement=connection.createStatement()) {
                try(var rows=statement.executeQuery("SELECT count(*),sum(is_hot),sum(sort) FROM tag")) {
                    assertTrue(rows.next());assertEquals(4,rows.getInt(1));assertEquals(3,rows.getInt(2));assertEquals(0,rows.getInt(3));
                }
                try(var rows=statement.executeQuery("SELECT to_regclass(current_schema() || '.home_tag_selection')")) {
                    assertTrue(rows.next());assertNull(rows.getString(1));
                }
            }
            assertThrows(java.sql.SQLException.class,()->schema.execute("UPDATE tag SET is_hot=2 WHERE id=1"));
            assertThrows(java.sql.SQLException.class,()->schema.execute("UPDATE tag SET is_hot=NULL WHERE id=1"));
        }
    }
    @Test void ordinaryTagCrudPersistsHotFlagsPreservesOmittedFlagAndAllowsMoreThanThreeHotTags() throws Exception {
        try(var schema=MediaPostgresTestSupport.createSchema()) {
            setup(schema);schema.executeDdl(RepositoryPaths.file("migration",MIGRATION));
            try(var session=factory(schema.name()).openSession(false)) {
                var repository=new MybatisTaxonomyRepository(session.getMapper(CategoryMapper.class),session.getMapper(TagMapper.class));
                for(long id=1;id<=4;id++)repository.saveTag(new TagDefinition(id,"tag"+id,"tag-"+id,null,0,1,1));
                session.commit();assertEquals(4,repository.listTag().stream().filter(tag->tag.isHot()==1).count());
                repository.saveTag(new TagDefinition(1L,"renamed","renamed",null,5,1));session.commit();
                assertEquals(1,repository.listTag().stream().filter(tag->tag.id()==1).findFirst().orElseThrow().isHot());
                repository.saveTag(new TagDefinition(1L,"renamed","renamed",null,5,1,0));session.commit();
                assertEquals(0,repository.listTag().stream().filter(tag->tag.id()==1).findFirst().orElseThrow().isHot());
                repository.deleteTag(2L);session.commit();
                assertEquals(List.of(4L,3L,1L),repository.listTag().stream().map(tag->tag.id()).toList());
                long id=repository.saveTag(new TagDefinition(null,"new","new",null,0,1));session.commit();
                assertEquals(0,repository.listTag().stream().filter(tag->tag.id()==id).findFirst().orElseThrow().isHot());
            }
        }
    }

    @Test void emptyOldConfigurationDefaultsToNoHotTags() throws Exception {
        try(var schema=MediaPostgresTestSupport.createSchema()) {
            setup(schema);schema.executeDdl(RepositoryPaths.file("migration",MIGRATION));
            try(var connection=schema.openConnection();var statement=connection.createStatement();var rows=statement.executeQuery("SELECT sum(is_hot) FROM tag")) {
                assertTrue(rows.next());assertEquals(0,rows.getInt(1));
            }
        }
    }

    @Test void unexpectedOldTableDependenciesAbortInsteadOfCascadingAndRollbackTheColumnChange() throws Exception {
        try(var schema=MediaPostgresTestSupport.createSchema()) {
            setup(schema);schema.execute("CREATE VIEW config_reader AS SELECT id FROM home_tag_selection");
            assertThrows(org.springframework.jdbc.datasource.init.ScriptException.class,
                    ()->schema.executeDdl(RepositoryPaths.file("migration",MIGRATION)));
            try(var connection=schema.openConnection();var statement=connection.createStatement()) {
                try(var rows=statement.executeQuery("SELECT count(*) FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='tag' AND column_name='is_hot'")) {
                    assertTrue(rows.next());assertEquals(0,rows.getInt(1));
                }
                try(var rows=statement.executeQuery("SELECT count(*) FROM home_tag_selection")) {assertTrue(rows.next());assertEquals(1,rows.getInt(1));}
            }
        }
    }
}
