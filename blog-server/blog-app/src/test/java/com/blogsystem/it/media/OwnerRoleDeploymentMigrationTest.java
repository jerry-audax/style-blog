class OwnerRoleDeploymentMigrationTest {
    private static final String SCRIPT = "015_20261025_add_missing_blog_owner_role_binding.sql";

    private void prepare(MediaPostgresTestSupport.ScopedSchema schema) throws Exception {
        schema.execute("CREATE TABLE sys_user(id BIGINT PRIMARY KEY,phone VARCHAR(20),password TEXT,status INTEGER,deleted INTEGER)");
        schema.execute("CREATE TABLE sys_role(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,role_code VARCHAR(50),role_name VARCHAR(50),status INTEGER,remark TEXT,deleted INTEGER)");
        schema.execute("CREATE UNIQUE INDEX role_code_unique ON sys_role(lower(role_code))");
        schema.execute("CREATE TABLE sys_user_role(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT REFERENCES sys_user(id),role_id BIGINT REFERENCES sys_role(id),UNIQUE(user_id,role_id))");
        schema.execute("CREATE TABLE sys_permission(id INTEGER PRIMARY KEY)");
        schema.execute("INSERT INTO sys_permission VALUES(77)");
        schema.execute("INSERT INTO sys_user VALUES(4,'19140838906','unchanged-hash',1,0),(8,'18800000000','other-hash',1,0)");
        schema.execute("INSERT INTO sys_role(role_code,role_name,status,deleted) VALUES('ADMIN','Admin',1,0),('USER','User',1,0)");
        schema.execute("INSERT INTO sys_user_role(user_id,role_id) VALUES(4,1),(4,2),(8,1)");
    }

    private void apply(MediaPostgresTestSupport.ScopedSchema schema) throws Exception {
        String sql = Files.readString(RepositoryPaths.file("migration", SCRIPT)).replace(":'owner_phone'", "'19140838906'");
        try (var connection = schema.openConnection()) {
            ScriptUtils.executeSqlScript(connection, new EncodedResource(new ByteArrayResource(sql.getBytes(StandardCharsets.UTF_8)), StandardCharsets.UTF_8));
        }
    }

    private long count(MediaPostgresTestSupport.ScopedSchema schema, String sql) throws Exception {
        try (var connection = schema.openConnection(); var statement = connection.createStatement(); var rows = statement.executeQuery(sql)) {
            assertTrue(rows.next()); return rows.getLong(1);
        }
    }

    @Test void grantsOnlyTheConfiguredOwnerAndPreservesLegacyRollbackData() throws Exception {
        try (var schema = MediaPostgresTestSupport.createSchema()) {
            prepare(schema); apply(schema);
            assertEquals(1, count(schema, "SELECT count(*) FROM sys_user_role ur JOIN sys_role r ON r.id=ur.role_id WHERE ur.user_id=4 AND r.role_code='BLOG_OWNER' AND r.status=1 AND r.deleted=0"));
            assertEquals(0, count(schema, "SELECT count(*) FROM sys_user_role ur JOIN sys_role r ON r.id=ur.role_id WHERE ur.user_id<>4 AND r.role_code='BLOG_OWNER'"));
            assertEquals(3, count(schema, "SELECT count(*) FROM sys_user_role WHERE role_id IN (1,2)"));
            assertEquals(2, count(schema, "SELECT count(*) FROM sys_role WHERE role_code IN ('ADMIN','USER')"));
            assertEquals(1, count(schema, "SELECT count(*) FROM sys_permission WHERE id=77"));
            assertEquals(1, count(schema, "SELECT count(*) FROM sys_user WHERE id=4 AND password='unchanged-hash'"));
        }
    }

    @Test void repeatedExecutionDoesNotDuplicateTheRoleOrBinding() throws Exception {
        try (var schema = MediaPostgresTestSupport.createSchema()) {
            prepare(schema); apply(schema); apply(schema);
            assertEquals(1, count(schema, "SELECT count(*) FROM sys_role WHERE role_code='BLOG_OWNER'"));
            assertEquals(4, count(schema, "SELECT count(*) FROM sys_user_role"));
        }
    }

    @Test void missingOrInactiveOwnerRollsBackWithoutCreatingARole() throws Exception {
        try (var schema = MediaPostgresTestSupport.createSchema()) {
            prepare(schema); schema.execute("UPDATE sys_user SET status=0 WHERE id=4");
            assertThrows(ScriptStatementFailedException.class, () -> apply(schema));
            assertEquals(2, count(schema, "SELECT count(*) FROM sys_role"));
            assertEquals(3, count(schema, "SELECT count(*) FROM sys_user_role"));
        }
    }

    @Test void inactiveExistingOwnerRoleIsNotReactivatedOrBypassed() throws Exception {
        try (var schema = MediaPostgresTestSupport.createSchema()) {
            prepare(schema);
            schema.execute("INSERT INTO sys_role(role_code,role_name,status,deleted) VALUES('BLOG_OWNER','Disabled owner',0,0)");
            assertThrows(ScriptStatementFailedException.class, () -> apply(schema));
            assertEquals(0, count(schema, "SELECT count(*) FROM sys_role WHERE role_code='BLOG_OWNER' AND status=1"));
            assertEquals(3, count(schema, "SELECT count(*) FROM sys_user_role"));
        }
    }

    @Test void realDatabaseRoleProviderReproduces403ThenAllowsTheSamePasswordSessionAfterUpgrade() throws Exception {
        try (var schema = MediaPostgresTestSupport.createSchema(); var auth = new CatalogMvcTestSupport();
                var context = new GenericApplicationContext()) {
            prepare(schema);
            var source = MediaCatalogRuntimeApiIntegrationTest.dataSource(schema.name());
            var configuration = new MybatisConfiguration();
            configuration.setMapUnderscoreToCamelCase(true);
            var factory = new SqlSessionFactoryBean();
            factory.setDataSource(source); factory.setConfiguration(configuration);
            SqlSessionFactory sessions = factory.getObject();
            context.registerBean("sqlSessionFactory", SqlSessionFactory.class, () -> sessions);
            var scanner = new ClassPathMapperScanner(context);
            scanner.setSqlSessionFactoryBeanName("sqlSessionFactory");
            scanner.registerFilters();
            scanner.scan("com.blogsystem.infrastructure.mybatis.mapper.identity");
            context.registerBean(StpInterfaceImpl.class);
            context.refresh();
            // 直接使用生产角色适配器，不能像普通接口夹具那样预设所有账号已有 BLOG_OWNER。
            SaManager.setStpInterface(context.getBean(StpInterfaceImpl.class));
            var credentials = new BcryptOwnerCredentials();
            String hash = credentials.encode("local-fixture-password");
            var owner = new OwnerAccount(4, "19140838906", "owner", null, null, null, hash, true);
            var accounts = mock(OwnerAccountRepository.class);
            when(accounts.findByPhone("19140838906")).thenReturn(Optional.of(owner));
            when(accounts.findById(4)).thenReturn(Optional.of(owner));
            when(accounts.findById(8)).thenReturn(Optional.of(new OwnerAccount(8,"18800000000","former-admin",null,null,null,hash,true)));
            var identity = new IdentityApplicationFacade(new SingleOwnerPolicy("19140838906"), accounts, credentials,
                    new SaTokenOwnerSession(), mock(LoginProtection.class));
            var administration = mock(AdministrationApplicationFacade.class);
            when(administration.dashboard()).thenReturn(new com.blogsystem.domain.administration.query.DashboardSummary(0,0,0,0,0,List.of()));
            var mvc = MockMvcBuilders.standaloneSetup(new AuthController(identity), new AdminController(administration))
                    .setControllerAdvice(new GlobalExceptionHandler())
                    .addInterceptors(new SingleOwnerSessionInterceptor(identity), new SaInterceptor()).build();
            var login = mvc.perform(post("/api/auth/login/password").contentType("application/json")
                    .content("{\"phone\":\"19140838906\",\"password\":\"local-fixture-password\"}"))
                    .andExpect(status().isOk()).andReturn().getResponse().getContentAsString();
            String token = new ObjectMapper().readTree(login).path("data").path("token").asText();
            assertFalse(token.isBlank());
            mvc.perform(get("/api/admin/dashboard").header("Authorization", token)).andExpect(status().isForbidden());
            apply(schema);
            mvc.perform(get("/api/admin/dashboard").header("Authorization", token)).andExpect(status().isOk());
            mvc.perform(get("/api/admin/dashboard")).andExpect(status().isUnauthorized());
            mvc.perform(get("/api/admin/dashboard").header("Authorization", auth.token(8))).andExpect(status().isForbidden());
            mvc.perform(post("/api/auth/login/password").contentType("application/json")
                    .content("{\"phone\":\"18800000000\",\"password\":\"local-fixture-password\"}"))
                    .andExpect(status().isUnauthorized());
        }
    }
}
